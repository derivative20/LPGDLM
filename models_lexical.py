def _no_grad_trunc_normal_(tensor, mean, std, a, b):
    # Cut & paste from PyTorch official master until it's in a few official releases - RW
    # Method based on https://people.sc.fsu.edu/~jburkardt/presentations/truncated_normal.pdf
    def norm_cdf(x):
        # Computes standard normal cumulative distribution function
        return (1. + math.erf(x / math.sqrt(2.))) / 2.

    if (mean < a - 2 * std) or (mean > b + 2 * std):
        warnings.warn("mean is more than 2 std from [a, b] in nn.init.trunc_normal_. "
                      "The distribution of values may be incorrect.",
                      stacklevel=2)

    with torch.no_grad():
        # Values are generated by using a truncated uniform distribution and
        # then using the inverse CDF for the normal distribution.
        # Get upper and lower cdf values
        l = norm_cdf((a - mean) / std)
        u = norm_cdf((b - mean) / std)

        # Uniformly fill tensor with values from [l, u], then translate to
        # [2l-1, 2u-1].
        tensor.uniform_(2 * l - 1, 2 * u - 1)

        # Use inverse cdf transform for normal distribution to get truncated
        # standard normal
        tensor.erfinv_()

        # Transform to proper mean, std
        tensor.mul_(std * math.sqrt(2.))
        tensor.add_(mean)

        # Clamp to ensure it's in the proper range
        tensor.clamp_(min=a, max=b)
        return tensor


def trunc_normal_(tensor, mean=0., std=1., a=-2., b=2.):
    # type: (Tensor, float, float, float, float) -> Tensor
    r"""Fills the input Tensor with values drawn from a truncated
    normal distribution. The values are effectively drawn from the
    normal distribution :math:`\mathcal{N}(\text{mean}, \text{std}^2)`
    with values outside :math:`[a, b]` redrawn until they are within
    the bounds. The method used for generating the random values works
    best when :math:`a \leq \text{mean} \leq b`.
    Args:
        tensor: an n-dimensional `torch.Tensor`
        mean: the mean of the normal distribution
        std: the standard deviation of the normal distribution
        a: the minimum cutoff value
        b: the maximum cutoff value
    Examples:
        >>> w = torch.empty(3, 5)
        >>> nn.init.trunc_normal_(w)
    """
    return _no_grad_trunc_normal_(tensor, mean, std, a, b)


class Uni_Sign(nn.Module):
    def __init__(self, args):
        super(Uni_Sign, self).__init__()
        self.args = args
        self.mask_id = 126336

        # Get LLaDA hidden size from config (lightweight, no model weight loading)
        _llada_config = AutoConfig.from_pretrained(llada_path, trust_remote_code=True)
        llada_hidden_size = _llada_config.hidden_size

        self.modes = ['body', 'left', 'right', 'face_all']
        
        self.graph, A = {}, []
        # project (x,y,score) to hidden dim
        hidden_dim = args.hidden_dim
        self.proj_linear = nn.ModuleDict()
        for mode in self.modes:
            self.graph[mode] = Graph(layout=f'{mode}', strategy='distance', max_hop=1)
            A.append(torch.tensor(self.graph[mode].A, dtype=torch.float32, requires_grad=False))
            self.proj_linear[mode] = nn.Linear(3, 64)

        self.gcn_modules = nn.ModuleDict()
        self.fusion_gcn_modules = nn.ModuleDict()
        spatial_kernel_size = A[0].size(0)
        for index, mode in enumerate(self.modes):
            self.gcn_modules[mode], final_dim = get_stgcn_chain(64, 'spatial', (1, spatial_kernel_size), A[index].clone(), True)
            self.fusion_gcn_modules[mode], _ = get_stgcn_chain(final_dim, 'temporal', (5, spatial_kernel_size), A[index].clone(), True)

        self.part_para = nn.Parameter(torch.zeros(hidden_dim*len(self.modes)))
        self.pose_proj = nn.Linear(256*4, llada_hidden_size)
        
        self.apply(self._init_weights)
        
        if "CSL" in self.args.dataset:
            self.lang = 'Chinese'
        else:
            self.lang = 'English'

        self.llada_model = AutoModel.from_pretrained(llada_path, trust_remote_code=True, torch_dtype=torch.bfloat16)
        self.llada_tokenizer = AutoTokenizer.from_pretrained(llada_path, trust_remote_code=True)
        # Cache wte reference before potential peft wrapping changes access path
        self.llada_wte = self.llada_model.model.transformer.wte
    
        
    def _init_weights(self, m):
        if isinstance(m, nn.Linear):
            trunc_normal_(m.weight, std=.02)
            if isinstance(m, nn.Linear) and m.bias is not None:
                nn.init.constant_(m.bias, 0)
        elif isinstance(m, nn.LayerNorm):
            nn.init.constant_(m.bias, 0)
            nn.init.constant_(m.weight, 1.0)

    def maybe_autocast(self, dtype=torch.float32):
        # if on cpu, don't use autocast
        # if on gpu, use autocast with dtype if provided, otherwise use torch.float16
        # enable_autocast = self.device != torch.device("cpu")
        enable_autocast = True

        if enable_autocast:
            return torch.cuda.amp.autocast(dtype=dtype)
        else:
            return contextlib.nullcontext()
    
    def forward_process(self, batch, total_dim=32000, eps=1e-3, eos_token_id=None):
        b, l = batch.shape
        t = torch.rand((b,), device=batch.device)

        p_mask = (1 - eps) * t + eps
        # p_mask = (1 - eps) * (0.5 + 0.5 * t) + eps
        p_mask = p_mask[:, None].repeat(1, l)

        mask_indices = torch.rand((b, l), device=batch.device) < p_mask
        noisy_batch = torch.where(mask_indices, total_dim, batch)

        return noisy_batch, p_mask, mask_indices   

    def forward(self, pose_input, text_input, phase="train"):
        features = []

        body_feat = None
        for part in self.modes:
            # project position to hidden dim
            proj_feat = self.proj_linear[part](pose_input[part]).permute(0,3,1,2) #B,C,T,V
            # spatial gcn forward
            gcn_feat = self.gcn_modules[part](proj_feat)
            if part == 'body':
                body_feat = gcn_feat

            else:
                assert not body_feat is None
                if part == 'left':                  
                    gcn_feat = gcn_feat + body_feat[..., -2][...,None].detach()
                    
                elif part == 'right':
                    gcn_feat = gcn_feat + body_feat[..., -1][...,None].detach()

                elif part == 'face_all':
                    gcn_feat = gcn_feat + body_feat[..., 0][...,None].detach()

                else:
                    raise NotImplementedError
            
            # temporal gcn forward
            gcn_feat = self.fusion_gcn_modules[part](gcn_feat) #B,C,T,V
            pool_feat = gcn_feat.mean(-1).transpose(1,2) #B,T,C
            features.append(pool_feat)
        
        # concat sub-pose feature across token dimension
        inputs_embeds = torch.cat(features, dim=-1) + self.part_para
        inputs_embeds = self.pose_proj(inputs_embeds)

        device = inputs_embeds.device

        if phase == "test":
            # For inference: return prompt embeddings (prefix + pose + header)
            pre_pose_embeds = self.llada_wte(text_input['pre_pose_ids'].to(device))
            pre_pose_attn = text_input['pre_attn_mask'].to(device)

            header_ids = text_input['header_ids'].to(device)
            header_embeds = self.llada_wte(header_ids)

            prompt_embeds = torch.cat([pre_pose_embeds, inputs_embeds, header_embeds], dim=1)
            prompt_attn = torch.cat([pre_pose_attn,
                                    pose_input['pose_attention_mask'],
                                    torch.ones(header_ids.shape, dtype=text_input['pre_attn_mask'].dtype, device=device)], dim=1)
            return {
                'inputs_embeds': prompt_embeds,
                'attention_mask': prompt_attn,
            }

        pre_pose_embeds = self.llada_wte(text_input['pre_pose_ids'].to(device))
        pre_pose_attn = text_input['pre_attn_mask'].to(device)

        post_pose_ids = text_input['post_pose_ids'].to(device)
        noise_ids = text_input['noise_ids'].to(device)
        post_pose_attn = text_input['post_attn_mask'].to(device)
        loss_pos = text_input['loss_pos']

        # Split post_pose into header (unmasked context) and content (masked target).
        HEADER_TOKEN_LEN = 7
        header_ids = post_pose_ids[:, :HEADER_TOKEN_LEN]
        content_ids = post_pose_ids[:, HEADER_TOKEN_LEN:]
        content_attn = post_pose_attn[:, HEADER_TOKEN_LEN:]

        # LLaDA masked diffusion training: only mask the content tokens
        masked_content_ids, p_mask, is_mask = self.forward_process(content_ids, total_dim=self.mask_id)

        header_embeds = self.llada_wte(header_ids)
        masked_content_embeds = self.llada_wte(masked_content_ids)

        # Full sequence: [prefix, pose, header(unmasked), content(masked)]
        shared_attn = torch.cat([
            pre_pose_attn,
            pose_input['pose_attention_mask'],
            post_pose_attn
        ], dim=1)

        full_embeds = torch.cat([pre_pose_embeds, inputs_embeds, header_embeds, masked_content_embeds], dim=1)

        # second loss
        # 这时使用的应该是全mask的序列
        # pure_noise_ids = noise_ids.clone()
        # for b in range(len(loss_pos)):
        #     pure_noise_ids[b , loss_pos[b]] = self.mask_id
        # pure_noise_embeds = self.llada_wte(pure_noise_ids)
        full_mask_content = torch.full_like(content_ids, self.mask_id)
        full_mask_embeds = self.llada_wte(full_mask_content)

        # # Full sequence: [prefix, pose, noise_embeds]
        # full_lexical_embeds = torch.cat([pre_pose_embeds, inputs_embeds, pure_noise_embeds], dim=1)
        # Full sequence: [prefix, pose, header(unmasked), content(masked)]
        full_lexical_embeds = torch.cat([pre_pose_embeds, inputs_embeds, header_embeds, full_mask_embeds], dim=1)

        combined_embeds = torch.cat([full_embeds, full_lexical_embeds], dim=0)  # [2B, seq, dim]
        combined_attn = torch.cat([shared_attn, shared_attn], dim=0)

        combined_out = self.llada_model(inputs_embeds=combined_embeds,
                    attention_mask=combined_attn,
                    return_dict=True)
        
        out_logits = combined_out.logits[:inputs_embeds.shape[0]]
        out_lexical_logits = combined_out.logits[inputs_embeds.shape[0]:]

        # Compute loss only on content positions (after header)
        content_start = pre_pose_embeds.shape[1] + inputs_embeds.shape[1] + HEADER_TOKEN_LEN
        # 使用 contiguous() 强制在内存上连续并从原 out 视图中分离出来
        content_logits = out_logits[:, content_start:, :].contiguous()
        content_lexical_logits = out_lexical_logits[:, content_start:, :].contiguous()

        # # release temp variables
        # del header_embeds, masked_content_embeds, full_embeds, full_lexical_embeds, combined_embeds
        # del combined_out, out_logits, out_lexical_logits
        # torch.cuda.empty_cache()

        loss_fct = torch.nn.CrossEntropyLoss(reduction='none')

        B, T_content = content_ids.shape
        per_token_loss = loss_fct(
            content_logits.reshape(-1, content_logits.shape[-1]),
            content_ids.reshape(-1).to(content_logits.device)
        ).reshape(B, T_content)

        # Importance weighting: divide by p_mask to correct for masking probability bias
        mask_indices = is_mask.bool()
        weighted_loss = per_token_loss[mask_indices] / p_mask[mask_indices].clamp(min=1e-6)
        # Normalize by total number of content tokens in batch
        total_tgt_tokens = content_attn.sum()
        loss = weighted_loss.sum() / total_tgt_tokens.clamp(min=1)

        # noise adding
        del mask_indices
        mask_indices = torch.zeros(B, T_content, dtype=torch.bool, device=content_lexical_logits.device)
    
        # 将 loss_pos 中指定位置设为 True
        for batch_idx, positions in enumerate(loss_pos):
            if len(positions) > 0:
                positions = [i-HEADER_TOKEN_LEN for i in positions]
                mask_indices[batch_idx, positions] = True
        
        noise_id_off_header = noise_ids[:, HEADER_TOKEN_LEN:]
        B1, T_content1 = noise_id_off_header.shape        
        per_token_loss_lex = loss_fct(
            content_lexical_logits.reshape(-1, content_lexical_logits.shape[-1]),
            content_ids.reshape(-1).to(content_lexical_logits.device)
        ).reshape(B1, T_content1)

        selected_loss = per_token_loss_lex[mask_indices]
        # total_tgt_tokens = content_attn.sum()
        # loss_lexical = selected_loss.sum() / total_tgt_tokens.clamp(min=1)
        loss_lexical = selected_loss.sum() / mask_indices.sum().clamp(min=1)

        total_loss = loss + self.args.lambda_lex * loss_lexical
        stack_out = {
            'total_loss': total_loss,
            'loss_main': loss,
            'loss_lexical': loss_lexical
        }

        return stack_out
    
    @torch.no_grad()
    def generate(self, pre_compute_item, max_new_tokens):
        inputs_embeds = pre_compute_item['inputs_embeds']
        attention_mask = pre_compute_item['attention_mask']

        prompt_len = inputs_embeds.shape[1]
        # Placeholder prompt ids (non-mask so they're treated as prompt tokens)
        input_prompt_ids = torch.full(
            (inputs_embeds.shape[0], prompt_len),
            self.llada_tokenizer.pad_token_id,
            dtype=torch.long,
            device=inputs_embeds.device
        )

        out = generate(
            self.llada_model,
            input_prompt_ids,
            inputs_embeds,
            attention_mask=attention_mask,
            gen_length=max_new_tokens,
            steps=max_new_tokens,
            block_length=max_new_tokens,
        )

        return out[:, prompt_len:]

def get_requires_grad_dict(model):
    param_requires_grad = {name: True for name, param in model.named_parameters()}
    param_requires_grad_right = {}
    for key in param_requires_grad.keys():
        if 'left' in key:
            param_requires_grad_right[key.replace("left", 'right')] = param_requires_grad[key]
    param_requires_grad = {**param_requires_grad,
                           **param_requires_grad_right}
    params_to_update = {k: v for k, v in model.state_dict().items() if param_requires_grad.get(k, True)}
    # # not saving llm weights
    # params_to_update = {k: v for k, v in model.state_dict().items()
    #                     if param_requires_grad.get(k, True) and not k.startswith('llada_model.')}

    return params_to_update

